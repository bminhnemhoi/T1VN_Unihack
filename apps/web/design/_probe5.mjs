import { chromium } from '@playwright/test';
const w = Number(process.argv[2]);
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: w, height: 900 }, hasTouch: w < 800 })).newPage();
await p.goto('http://localhost:3102/', { waitUntil: 'networkidle' });
await p.waitForTimeout(3500);
await p.locator('#cong-nghe').evaluate((el) => window.scrollTo(0, el.getBoundingClientRect().top + scrollY + 380));
await p.waitForTimeout(250);
await p.screenshot({ path: `/tmp/claude-1000/tech2-${w}-a.png` });
await p.waitForTimeout(1600);
await p.screenshot({ path: `/tmp/claude-1000/tech2-${w}-b.png` });
console.log(await p.evaluate(() => [...document.querySelectorAll('[data-lp-tech-card]')].map((c) => getComputedStyle(c).opacity)));
await b.close();
